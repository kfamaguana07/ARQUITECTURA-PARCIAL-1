IF DB_ID('BANQUITO_CORE') IS NOT NULL
BEGIN
    USE master;
    ALTER DATABASE BANQUITO_CORE SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE BANQUITO_CORE;
END;
GO

CREATE DATABASE BANQUITO_CORE;
GO

USE BANQUITO_CORE;
GO

-- Tabla: CLIENTE
CREATE TABLE CLIENTE (
   COD_CLIENTE          INT IDENTITY(1,1)    NOT NULL,
   CEDULA               VARCHAR(100)         NOT NULL UNIQUE,
   NOMBRE               VARCHAR(100)         NOT NULL,
   GENERO               VARCHAR(1)           NOT NULL CHECK (GENERO IN ('M', 'F')),
   FECHA_NACIMIENTO     DATE                 NOT NULL,
   CONSTRAINT PK_CLIENTE PRIMARY KEY (COD_CLIENTE)
);
GO

-- Tabla: CUENTA
CREATE TABLE CUENTA (
   NUM_CUENTA           VARCHAR(8)           NOT NULL,
   COD_CLIENTE          INT                  NOT NULL,
   SALDO                NUMERIC(10,2)        NOT NULL DEFAULT 0.00,
   CONSTRAINT PK_CUENTA PRIMARY KEY (NUM_CUENTA),
   CONSTRAINT FK_CUENTA_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE)
);
GO

-- Tabla: MOVIMIENTO
CREATE TABLE MOVIMIENTO (
   COD_MOVIMIENTO       INT IDENTITY(1,1)    NOT NULL,
   NUM_CUENTA           VARCHAR(8)           NOT NULL,
   TIPO                 VARCHAR(3)           NOT NULL CHECK (TIPO IN ('DEP', 'RET')),
   VALOR                NUMERIC(10,2)        NOT NULL,
   FECHA                DATETIME             NOT NULL DEFAULT GETDATE(),
   CONSTRAINT PK_MOVIMIENTO PRIMARY KEY (COD_MOVIMIENTO),
   CONSTRAINT FK_MOVIMIENTO_CUENTA FOREIGN KEY (NUM_CUENTA) REFERENCES CUENTA (NUM_CUENTA)
);
GO

-- Tabla: CREDITO
CREATE TABLE CREDITO (
   COD_CREDITO          INT IDENTITY(1,1)    NOT NULL,
   COD_CLIENTE          INT                  NOT NULL,
   MONTO                NUMERIC(10,2)        NOT NULL,
   PLAZO_MESES          INT                  NOT NULL CHECK (PLAZO_MESES BETWEEN 3 AND 18),
   TASA_INTERES         NUMERIC(5,2)         NOT NULL DEFAULT 16.50,
   FECHA_CREACION       DATETIME             NOT NULL DEFAULT GETDATE(),
   CONSTRAINT PK_CREDITO PRIMARY KEY (COD_CREDITO),
   CONSTRAINT FK_CREDITO_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE)
);
GO

-- Tabla: AMORTIZACION
CREATE TABLE AMORTIZACION (
   COD_AMORTIZACION     INT IDENTITY(1,1)    NOT NULL,
   COD_CREDITO          INT                  NOT NULL,
   NUM_CUOTA            INT                  NOT NULL,
   VALOR_CUOTA          NUMERIC(10,2)        NOT NULL,
   INTERES_PAGADO       NUMERIC(10,2)        NOT NULL,
   CAPITAL_PAGADO       NUMERIC(10,2)        NOT NULL,
   SALDO_RESTANTE       NUMERIC(10,2)        NOT NULL,
   CONSTRAINT PK_AMORTIZACION PRIMARY KEY (COD_AMORTIZACION),
   CONSTRAINT FK_AMORTIZACION_CREDITO FOREIGN KEY (COD_CREDITO) REFERENCES CREDITO (COD_CREDITO)
);
GO